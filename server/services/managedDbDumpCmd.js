/**
 * Logical dumps and restores of ONE managed database — the argv and SQL
 * builders.
 *
 * PURE, like managedDbTls.js / managedMongo.js / managedRedis.js: this file
 * returns argv arrays and SQL strings, services/managedDbBackup.js runs them.
 * That split is what lets test/managed-db-backup.test.js pin the exact
 * single-database scope and the absence of any credential in argv without a
 * daemon.
 *
 * =========================================================================
 * THREE RULES EVERY BUILDER HERE KEEPS
 * =========================================================================
 * 1. ONE DATABASE. Every dump names exactly the database it is for, as a
 *    positional argument the tool reads as "this database only":
 *      pg_dump -d <db>            (never pg_dumpall)
 *      mariadb-dump <db>          (never --all-databases, never --databases:
 *                                  that form also writes CREATE DATABASE/USE,
 *                                  which would let a restore pick its target)
 *      mongodump --db <db>        (and mongorestore --nsInclude '<db>.*')
 *      redis                      an instance IS one scope's container
 *    A backup of app X therefore cannot contain app Y's tables, and the test
 *    file asserts it per engine.
 *
 * 2. NO PASSWORD IN ARGV. argv is world-readable in the host's process table.
 *      postgres  docker exec -u postgres over the unix socket, which the image
 *                trusts (pg_hba line 1, managedDbTls.pgHbaConf) — no password
 *                exists on this path at all.
 *      mariadb   dumps: /root/.my.cnf, planted over stdin by managedDb's
 *                ensureAdminCredentialFile(). Restores run as the APP login
 *                (see restoreArgs) with MYSQL_PWD passed by name through
 *                `docker exec -e`.
 *      mongo     a --config file written INSIDE the container over stdin
 *                (mongoConfigBody), removed afterwards. mongodump/mongorestore
 *                read `password:` from it; the username is not a secret.
 *      redis     redis-cli takes REDISCLI_AUTH from the container's own env.
 *
 * 3. NOTHING REACHES A SHELL AS SOURCE. Where a shell is unavoidable (mongo's
 *    `$(hostname -i)`, the redis file swap) the script is a FIXED literal and
 *    the variable parts arrive as positional parameters ("$1", "$2"), which a
 *    shell substitutes as data, never parses. The database names are
 *    additionally assertIdent'd by the caller — a-z, 0-9, underscore.
 */

import { pgDumpExcludeArgs } from './managedDbStats.js';
import { OOM_DB_FLAG } from './oomPriority.js';

const SAFE_IDENT = /^[a-z][a-z0-9_]{0,62}$/;

function ident(name) {
  if (!SAFE_IDENT.test(String(name)) || Buffer.byteLength(String(name)) > 31) {
    throw new Error(`managedDbDumpCmd: refusing identifier ${JSON.stringify(name)}`);
  }
  return name;
}

function port(p) {
  const n = Number(p);
  if (!Number.isInteger(n) || n <= 0 || n > 65535) throw new Error(`managedDbDumpCmd: bad port ${JSON.stringify(p)}`);
  return String(n);
}

// Container-side scratch path for mongo's tool config. Generated by the
// caller from random hex, checked here so a malformed one is never written.
const CONF_RE = /^\/tmp\/appcrane-mongotool-[0-9a-f]{16,64}\.yaml$/;
function confPath(p) {
  if (!CONF_RE.test(String(p))) throw new Error(`managedDbDumpCmd: refusing config path ${JSON.stringify(p)}`);
  return p;
}

/** The names a Postgres restore stages into, derived from the real one. */
export function pgStagingName(database) {
  // `_r` is never produced by managedDb.namesForScope (it ends in a digit,
  // `_sandbox`, `_t<hex>` or `_u`), so the staging database cannot be another
  // scope's real database, and 31 bytes still holds for the longest real name
  // (crane_a<id>_t<12 hex>_r).
  return ident(`${ident(database)}_r`);
}

// ---------------------------------------------------------------------------
// Dumps (stdout of the docker exec is the dump)
// ---------------------------------------------------------------------------

/**
 * argv for `docker` that writes a dump of ONE database to stdout.
 *
 *   postgres  custom format (-Fc): compressed, and the only format
 *             pg_restore can selectively --clean / reorder. --no-password
 *             makes a misconfigured socket fail instead of prompting forever.
 *   mariadb   --single-transaction: a consistent InnoDB snapshot without
 *             locking the app out. --routines --triggers: the objects that
 *             live in the schema but are not tables. --hex-blob: binary
 *             columns survive a charset round-trip. --skip-ssl is NOT needed:
 *             the admin path is the unix socket (my.cnf protocol=socket).
 *   mongo     --archive --gzip to stdout; one stream, no directory tree.
 */
export function dumpArgs(engine, { container, database, port: p, configPath, pgKeepExtensions = null } = {}) {
  ident(database);
  if (engine === 'postgres') {
    // pgKeepExtensions (an array) means the database carries AppCrane's
    // pg_stat_statements wiring, which the dump leaves out — see
    // managedDbStats.parseDumpExtensions for why, and pgDumpExcludeArgs for how.
    return ['exec', '-u', 'postgres', container,
      'pg_dump', '-U', 'postgres', '--no-password', '--format=custom', '-d', database,
      ...(Array.isArray(pgKeepExtensions) ? pgDumpExcludeArgs(pgKeepExtensions) : [])];
  }
  if (engine === 'mariadb') {
    return ['exec', container,
      'mariadb-dump', '--single-transaction', '--routines', '--triggers', '--hex-blob', database];
  }
  if (engine === 'mongo') {
    return ['exec', container, 'sh', '-c',
      'exec mongodump --host "$(hostname -i)" --port "$1" --username root --authenticationDatabase admin'
      + ' --config "$2" --db "$3" --archive --gzip',
      'sh', port(p), confPath(configPath), database];
  }
  if (engine === 'redis') {
    // After BGSAVE has finished (managedDbBackup waits for it). The data
    // directory is the instance's own; nothing else lives in it.
    return ['exec', container, 'cat', '/data/dump.rdb'];
  }
  throw new Error(`managedDbDumpCmd: no dump for engine '${engine}'`);
}

// ---------------------------------------------------------------------------
// Restores (stdin of the docker exec is the dump)
// ---------------------------------------------------------------------------

/**
 * argv for `docker` that loads a dump from stdin into ONE database.
 *
 * THE SESSION USER IS THE APP'S OWN LOGIN, on every engine. A dump is
 * app-authored content: functions, triggers, CHECK constraints, defaults and
 * index expressions the app owner wrote, and some of them EXECUTE while the
 * dump loads (an index on an expression calls its function; a CHECK runs for
 * every restored row). Loaded by the superuser, any of them could act as the
 * superuser across the shared server. An earlier draft used pg_restore
 * `-U postgres --role <app>`, which is NOT enough: --role only sets the
 * CURRENT role, and a function can `RESET ROLE` back to the superuser session
 * user. So the restoring session itself is the app login, and the admin-only
 * steps (create/drop the database, grants, the login policy) are separate
 * admin statements that never execute dump content.
 *
 *   postgres  `-U <app login>` over the container's UNIX SOCKET into the
 *             STAGING database. pg_hba line 1 (`local all all trust`,
 *             managedDbTls.pgHbaConf) authenticates it with no password: only
 *             processes inside the server container reach that socket, and
 *             the hostssl+certificate rule for manifest logins governs TCP,
 *             which this does not use. --no-owner: objects are owned by the
 *             session user, i.e. the app. --single-transaction +
 *             --exit-on-error: a dump that fails half-way leaves the staging
 *             database to be dropped, and the live one untouched.
 *   mariadb   as the app login over TCP to 127.0.0.1 INSIDE the container,
 *             with TLS verified against the server's CA (127.0.0.1 is in the
 *             server certificate) and, for a certificate-required login, its
 *             own client certificate (written into a private scratch dir over
 *             stdin, removed afterwards). The password arrives as MYSQL_PWD
 *             through `docker exec -e MYSQL_PWD` — the NAME is in argv, the
 *             value only in the docker CLI's environment. --no-defaults keeps
 *             the root credential file (/root/.my.cnf) out of it. A DEFINER
 *             naming another user then fails (the app has no SET USER
 *             privilege) instead of being honoured. --one-database ignores
 *             statements aimed at another database, --sandbox refuses the
 *             client's shell/file commands (\!, source).
 *   mongo     as the app login: a certificate login authenticates
 *             MONGODB-X509 with its own client PEM, a password login with a
 *             --config file holding its password. Both inside the scratch
 *             dir. The login's roles (readWrite + dbAdmin on its own
 *             database) bound what the restore can touch, and --nsInclude
 *             '<db>.*' skips anything else an archive holds; --drop replaces
 *             each collection rather than merging into it.
 */
export function restoreArgs(engine, { container, database, username, port: p, scratch, certRequired = false } = {}) {
  ident(database);
  ident(username);
  if (engine === 'postgres') {
    // statement_timeout=0 for this session only: the login carries the
    // platform's per-statement cap as a role default (managedDbTls
    // loginPolicySql), and one COPY or CREATE INDEX of a large table can
    // legitimately outlast it. A login may lower or lift its own setting, so
    // this grants nothing the app could not already do.
    return ['exec', '-i', '-u', 'postgres', '-e', 'PGOPTIONS=-c statement_timeout=0', container,
      'pg_restore', '-U', username, '--no-password', '-d', pgStagingName(database),
      '--no-owner', '--exit-on-error', '--single-transaction'];
  }
  if (engine === 'mariadb') {
    const dir = scratchDir(scratch);
    return ['exec', '-i', '-e', 'MYSQL_PWD', container, 'mariadb', '--no-defaults',
      '--protocol=tcp', '--host=127.0.0.1', '--port=3306', `--user=${username}`,
      '--ssl', '--ssl-verify-server-cert', `--ssl-ca=${SERVER_CA}`,
      ...(certRequired ? [`--ssl-cert=${dir}/client.crt`, `--ssl-key=${dir}/client.key`] : []),
      // Same reason as statement_timeout above: MAX_STATEMENT_TIME is the
      // login's session default, and the session may set its own.
      '--init-command=SET SESSION max_statement_time=0',
      '--batch', '--sandbox', '--one-database', database];
  }
  if (engine === 'mongo') {
    const dir = scratchDir(scratch);
    const auth = certRequired
      ? ' --sslPEMKeyFile "$2/client.pem" --authenticationMechanism MONGODB-X509 --authenticationDatabase \'$external\''
      : ' --username "$4" --authenticationDatabase "$3" --config "$2/app.yaml"';
    return ['exec', '-i', container, 'sh', '-c',
      'exec mongorestore --host 127.0.0.1 --port "$1" --ssl --sslCAFile ' + SERVER_CA + auth
      + ' --nsInclude "$3.*" --drop --archive --gzip',
      'sh', port(p), dir, database, username];
  }
  throw new Error(`managedDbDumpCmd: no streamed restore for engine '${engine}' (redis restores by file swap)`);
}

// The server's own CA copy inside its container (managedDbTls.installSnippet
// puts it there at start), used to verify the server from the inside.
const SERVER_CA = '/tmp/appcrane-tls/ca.crt';

// Private per-restore scratch directory inside the server container, for the
// app login's client certificate / tool config. Random hex from the caller.
const SCRATCH_RE = /^\/tmp\/appcrane-restore-[0-9a-f]{16,64}$/;
function scratchDir(d) {
  if (!SCRATCH_RE.test(String(d))) throw new Error(`managedDbDumpCmd: refusing scratch dir ${JSON.stringify(d)}`);
  return d;
}

const SCRATCH_FILES = new Set(['client.crt', 'client.key', 'client.pem', 'app.yaml']);

/** docker argv writing one scratch file (body on stdin), 0600 in a 0700 dir. */
export function scratchWriteArgs(container, dir, name) {
  if (!SCRATCH_FILES.has(name)) throw new Error(`managedDbDumpCmd: refusing scratch file ${JSON.stringify(name)}`);
  return ['exec', '-i', container, 'sh', '-c', 'umask 077 && mkdir -p "$1" && cat > "$1/$2"', 'sh', scratchDir(dir), name];
}

export function scratchRemoveArgs(container, dir) {
  return ['exec', container, 'rm', '-rf', scratchDir(dir)];
}

/**
 * Redis: write the RDB into a STOPPED instance's data directory from a
 * throwaway container of the same image (root in its own namespace, so it can
 * write a directory the redis uid owns on Linux — the same reason
 * docker.removeTreeAsRoot exists). Written to a temp name and renamed, so a
 * truncated upload never becomes dump.rdb.
 */
export function redisSwapArgs({ hostDir, image }) {
  if (!hostDir || typeof hostDir !== 'string' || hostDir.includes(':')) {
    throw new Error('managedDbDumpCmd: bad redis data directory');
  }
  return ['run', '--rm', '-i', OOM_DB_FLAG, '--network', 'none', '-v', `${hostDir}:/data`, '--entrypoint', 'sh', image, '-c',
    'cat > /data/.appcrane-restore.rdb && chown redis:redis /data/.appcrane-restore.rdb'
    + ' && mv -f /data/.appcrane-restore.rdb /data/dump.rdb'];
}

/** docker argv to write mongo's tool config inside the container (body on stdin). */
export function mongoConfigWriteArgs(container, configPath) {
  return ['exec', '-i', container, 'sh', '-c', 'umask 077 && cat > "$1"', 'sh', confPath(configPath)];
}

export function mongoConfigRemoveArgs(container, configPath) {
  return ['exec', container, 'rm', '-f', confPath(configPath)];
}

/**
 * The --config body: the password only, quoted so a value that happens to
 * look like a YAML number or boolean stays a string. The caller has run it
 * through assertPassword (base64url: no quote, no backslash, no newline), so
 * it cannot close the quotes.
 */
export function mongoConfigBody(adminPassword) {
  if (!/^[A-Za-z0-9_-]{24,128}$/.test(String(adminPassword))) {
    throw new Error('managedDbDumpCmd: admin password outside the safe alphabet');
  }
  return `password: "${adminPassword}"\n`;
}

// ---------------------------------------------------------------------------
// SQL around a restore
// ---------------------------------------------------------------------------

/**
 * Postgres: create the staging database exactly as provisioning creates a
 * real one (managedDb.provisionSql): owned by the app role, CONNECT revoked
 * from PUBLIC. Any leftover staging database from an interrupted restore is
 * dropped first.
 */
export function pgPrepareStagingSql(database, username) {
  const s = pgStagingName(database);
  ident(username);
  return [
    `DROP DATABASE IF EXISTS "${s}" WITH (FORCE);`,
    `CREATE DATABASE "${s}" OWNER "${username}";`,
    `REVOKE ALL ON DATABASE "${s}" FROM PUBLIC;`,
    `GRANT CONNECT, TEMPORARY ON DATABASE "${s}" TO "${username}";`,
  ].join('\n');
}

/** The per-database grants provisioning applies inside a new database. */
export function pgSchemaGrantsSql(username) {
  ident(username);
  return [
    'REVOKE ALL ON SCHEMA public FROM PUBLIC;',
    `ALTER SCHEMA public OWNER TO "${username}";`,
    `GRANT ALL ON SCHEMA public TO "${username}";`,
  ].join('\n');
}

/**
 * Swap the restored staging database in. WITH (FORCE) ends the app's open
 * sessions — the restore replaces the data they were reading anyway, and a
 * session left open would make the drop wait forever. Nothing is dropped
 * until pg_restore has succeeded; the caller only runs this afterwards.
 */
export function pgSwapSql(database, username) {
  const s = pgStagingName(database);
  ident(username);
  return [
    `DROP DATABASE IF EXISTS "${ident(database)}" WITH (FORCE);`,
    `ALTER DATABASE "${s}" RENAME TO "${database}";`,
    `REVOKE ALL ON DATABASE "${database}" FROM PUBLIC;`,
    `GRANT CONNECT, TEMPORARY ON DATABASE "${database}" TO "${username}";`,
  ].join('\n');
}

export function pgDropStagingSql(database) {
  return `DROP DATABASE IF EXISTS "${pgStagingName(database)}" WITH (FORCE);`;
}

/** MariaDB: lock / unlock the app's login for the length of a restore. */
export function mariadbLockSql(username, lock) {
  return `ALTER USER '${ident(username)}'@'%' ACCOUNT ${lock ? 'LOCK' : 'UNLOCK'};\n`;
}

/** MariaDB: the app login's live sessions, one numeric id per line. */
export function mariadbSessionsSql(username) {
  return `SELECT ID FROM information_schema.PROCESSLIST WHERE USER = '${ident(username)}';\n`;
}

/** KILL statements for ids read back from mariadbSessionsSql — digits only. */
export function mariadbKillSql(ids) {
  return ids.filter((id) => /^\d+$/.test(String(id))).map((id) => `KILL CONNECTION ${id};`).join('\n');
}

/**
 * MariaDB: recreate the database empty, with the same character set
 * provisioning uses. The login and its grant are server-level and survive a
 * DROP DATABASE by name; the GRANT is re-asserted anyway, after the load, by
 * the policy step.
 */
export function mariadbRecreateSql(database) {
  ident(database);
  return [
    `DROP DATABASE IF EXISTS \`${database}\`;`,
    `CREATE DATABASE \`${database}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;`,
  ].join('\n');
}

export function mariadbGrantSql(database, username) {
  return [
    `GRANT ALL PRIVILEGES ON \`${ident(database)}\`.* TO '${ident(username)}'@'%';`,
    'FLUSH PRIVILEGES;',
  ].join('\n');
}

/**
 * Mongo: empty the database before mongorestore so collections created after
 * the backup do not survive a "restore". dropDatabase leaves the app's users
 * alone — they live in admin.system.users, not in this database — which the
 * real-engine run confirmed (the login still authenticates afterwards).
 */
export function mongoDropDatabaseScript(adminPassword, database) {
  // Same auth line managedMongo's scripts start with; the password is checked
  // against the base64url alphabet by mongoConfigBody's rule before use.
  mongoConfigBody(adminPassword);
  return [
    `db.getSiblingDB('admin').auth('root', '${adminPassword}');`,
    `db.getSiblingDB(${JSON.stringify(ident(database))}).dropDatabase();`,
    'print("MONGO_EMPTIED");',
  ].join('\n') + '\n';
}
