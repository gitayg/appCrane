import { CONTAINER_PORT } from './detect.js';
import { has, jsonOf } from './projectFiles.js';

// The files AppCrane adds so an adopted project builds and passes the deploy
// health gate. Only files the project does not already have are generated, and
// every one is minimal and framework-appropriate. The deployer validates a
// committed Dockerfile (EXPOSE 3000, non-root USER, no ENV secrets), so these
// satisfy that contract by construction.

export const SERVE_FILE = 'appcrane-serve.mjs';

// Dependency-free static server: serves the build output, falls back to
// index.html for client-side routes, and answers the health contract.
const SERVE_SOURCE = `import { createServer } from 'node:http';
import { createReadStream, readFileSync, statSync } from 'node:fs';
import { extname, join, normalize, sep } from 'node:path';

const root = normalize(join(process.cwd(), process.env.APPCRANE_STATIC_DIR || 'dist'));
const port = Number(process.env.PORT || ${CONTAINER_PORT});
let version = '0.0.0';
try { version = JSON.parse(readFileSync('package.json', 'utf8')).version || version; } catch {}
const types = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css',
  '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
  '.gif': 'image/gif', '.webp': 'image/webp', '.ico': 'image/x-icon', '.woff': 'font/woff', '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8', '.map': 'application/json', '.webmanifest': 'application/manifest+json',
};

function fileFor(urlPath) {
  let p;
  try { p = decodeURIComponent(urlPath.split('?')[0]); } catch { return null; }
  const abs = normalize(join(root, p));
  if (abs !== root && !abs.startsWith(root + sep)) return null;
  try { if (statSync(abs).isFile()) return abs; } catch {}
  return null;
}

createServer((req, res) => {
  if (req.url === '/api/health' || req.url.startsWith('/api/health?')) {
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ status: 'ok', version }));
    return;
  }
  if (req.method !== 'GET' && req.method !== 'HEAD') { res.writeHead(405); res.end(); return; }
  let file = fileFor(req.url);
  if (!file && !extname(req.url.split('?')[0])) file = fileFor('/index.html');
  if (!file) { res.writeHead(404, { 'content-type': 'text/plain' }); res.end('Not found'); return; }
  const type = types[extname(file).toLowerCase()] || 'application/octet-stream';
  const cache = /\\/assets\\//.test(file) ? 'public, max-age=31536000, immutable' : 'no-cache';
  res.writeHead(200, { 'content-type': type, 'cache-control': cache });
  if (req.method === 'HEAD') { res.end(); return; }
  createReadStream(file).pipe(res);
}).listen(port, '0.0.0.0', () => console.log('serving ' + root + ' on ' + port));
`;

function installCmd(pm, { prodOnly = false } = {}) {
  if (pm === 'pnpm') return `pnpm install ${prodOnly ? '--prod ' : ''}--frozen-lockfile`;
  if (pm === 'yarn') return `yarn install ${prodOnly ? '--production ' : ''}--frozen-lockfile`;
  const omit = prodOnly ? ' --omit=dev' : '';
  return `if [ -f package-lock.json ]; then npm ci${omit}; else npm install${omit}; fi`;
}

function copyManifests(pm) {
  if (pm === 'pnpm') return 'COPY --chown=node:node package.json pnpm-lock.yaml ./';
  if (pm === 'yarn') return 'COPY --chown=node:node package.json yarn.lock ./';
  return 'COPY --chown=node:node package*.json ./';
}

function nodeHead(pm) {
  return [
    'FROM node:20-alpine AS build',
    'ARG APP_BASE_PATH=/',
    'ENV APP_BASE_PATH=$APP_BASE_PATH',
    ...(pm === 'pnpm' || pm === 'yarn' ? ['RUN corepack enable'] : []),
    'WORKDIR /app',
    'RUN chown node:node /app',
    'USER node',
  ];
}

function spaDockerfile(project) {
  const pm = project.package_manager;
  const build = project.build;
  const out = project.output_dir || 'dist';
  return [
    '# Generated by AppCrane adoption: build the single-page app, then serve the',
    '# output with a dependency-free static server that also answers /api/health.',
    ...nodeHead(pm),
    copyManifests(pm),
    `RUN ${installCmd(pm)}`,
    'COPY --chown=node:node . .',
    `RUN ${build}`,
    '',
    'FROM node:20-alpine',
    'WORKDIR /app',
    'ENV NODE_ENV=production',
    `ENV APPCRANE_STATIC_DIR=${out}`,
    `COPY --from=build --chown=node:node /app/${out} ./${out}`,
    'COPY --from=build --chown=node:node /app/package.json ./package.json',
    `COPY --chown=node:node ${SERVE_FILE} ./${SERVE_FILE}`,
    'USER node',
    `EXPOSE ${CONTAINER_PORT}`,
    `CMD ["node", "${SERVE_FILE}"]`,
    '',
  ].join('\n');
}

function staticDockerfile() {
  return [
    '# Generated by AppCrane adoption: serve the static files and answer /api/health.',
    'FROM node:20-alpine',
    'WORKDIR /app',
    'RUN chown node:node /app',
    'ENV NODE_ENV=production',
    'ENV APPCRANE_STATIC_DIR=.',
    'COPY --chown=node:node . .',
    'USER node',
    `EXPOSE ${CONTAINER_PORT}`,
    `CMD ["node", "${SERVE_FILE}"]`,
    '',
  ].join('\n');
}

function nodeServerDockerfile(project) {
  const pm = project.package_manager;
  const start = project.start || 'npm start';
  return [
    `# Generated by AppCrane adoption: ${project.label}. Installs with dev`,
    '# dependencies (the build usually needs them), builds, then starts.',
    ...nodeHead(pm),
    copyManifests(pm),
    `RUN ${installCmd(pm)}`,
    'COPY --chown=node:node . .',
    ...(project.build ? [`RUN ${project.build}`] : []),
    'ENV NODE_ENV=production',
    `ENV PORT=${CONTAINER_PORT}`,
    `EXPOSE ${CONTAINER_PORT}`,
    `CMD ["sh", "-c", ${JSON.stringify(start)}]`,
    '',
  ].join('\n');
}

function pythonDockerfile(project) {
  const extra = (project.python_needs || []).join(' ');
  const start = project.start || 'python main.py';
  const reqs = project.has_requirements;
  return [
    `# Generated by AppCrane adoption: ${project.label}.`,
    'FROM python:3.12-slim',
    'WORKDIR /app',
    'RUN useradd --create-home --uid 1000 app && chown app:app /app',
    ...(reqs ? ['COPY requirements.txt ./', 'RUN pip install --no-cache-dir -r requirements.txt'] : []),
    ...(extra ? [`RUN pip install --no-cache-dir ${extra}`] : []),
    'COPY --chown=app:app . .',
    ...(!reqs && project.has_pyproject ? ['RUN pip install --no-cache-dir .'] : []),
    'USER app',
    `ENV PORT=${CONTAINER_PORT}`,
    `EXPOSE ${CONTAINER_PORT}`,
    `CMD ["sh", "-c", ${JSON.stringify(start)}]`,
    '',
  ].join('\n');
}

const NEXT_HEALTH_APP = (version) => `export const dynamic = 'force-dynamic';

export function GET() {
  return Response.json({ status: 'ok', version: ${JSON.stringify(version)} });
}
`;
const NEXT_HEALTH_PAGES = (version) => `export default function handler(_req, res) {
  res.status(200).json({ status: 'ok', version: ${JSON.stringify(version)} });
}
`;

/**
 * Files to add: [{ path, content, why }]. Never overwrites a file the project has.
 */
export function scaffoldFiles(files, project, { name }) {
  const out = [];
  const add = (path, content, why) => { if (!has(files, path)) out.push({ path, content, why }); };
  const pkg = jsonOf(files, 'package.json');
  const version = String(pkg?.version || '0.1.0');
  const kind = project.kind;
  project = { ...project, has_requirements: has(files, 'requirements.txt'), has_pyproject: has(files, 'pyproject.toml') };

  if (!project.has_dockerfile) {
    if (kind === 'spa' && project.build) {
      add('Dockerfile', spaDockerfile(project), 'Builds the app and serves the output; AppCrane runs every app as a container on port 3000.');
      add(SERVE_FILE, SERVE_SOURCE, 'Static server with client-side route fallback and the /api/health answer AppCrane checks after each deploy.');
    } else if (kind === 'static') {
      add('Dockerfile', staticDockerfile(), 'Serves the static files on port 3000.');
      add(SERVE_FILE, SERVE_SOURCE, 'Static server that also answers /api/health.');
    } else if (project.framework === 'next') {
      add('Dockerfile', nodeServerDockerfile(project), 'Builds and starts Next.js on port 3000.');
    } else if (project.runtime === 'node' && project.start) {
      add('Dockerfile', nodeServerDockerfile(project), `Builds and starts the ${project.label} on port 3000.`);
    } else if (project.runtime === 'python' && project.start) {
      add('Dockerfile', pythonDockerfile(project), `Installs and starts the ${project.label} on port 3000.`);
    }
  }

  if (project.framework === 'next' && !project.health_route && project.router) {
    if (project.router.type === 'app') {
      add(`${project.router.dir}/api/health/route.js`, NEXT_HEALTH_APP(version), 'Answers the /api/health check AppCrane runs after each deploy.');
    } else {
      add(`${project.router.dir}/api/health.js`, NEXT_HEALTH_PAGES(version), 'Answers the /api/health check AppCrane runs after each deploy.');
    }
  }

  if (!project.has_manifest) {
    const manifest = { name, version, be: { health: '/api/health' } };
    add('deployhub.json', `${JSON.stringify(manifest, null, 2)}\n`, 'Tells AppCrane where the health endpoint is.');
  }

  if (out.some((f) => f.path === 'Dockerfile')) {
    add('.dockerignore', 'node_modules\n.git\n.next\ndist\nbuild\n.output\n__pycache__\n.venv\n', 'Keeps dependencies and old build output out of the image build.');
  }
  return out;
}
