test('Cargo.lock reports registry crates and not the local crate', () => {
  const pkgs = parse(fixture('Cargo.lock', CARGO_LOCK));
  assert.deepEqual(idsOf(pkgs), ['libc@0.2.147', 'time@0.2.22'],
    'the workspace/root crate has no `source` because Cargo did not fetch it — it is ' +
    'published nowhere, so a query either matches nothing or matches an unrelated ' +
    'crate that happens to share the name');
});

test('a [[patch.unused]] block is neither a package nor a rename of the last one', () => {
  // It carries `name` and `version` at the same nesting a package does. A
  // reader that does not namespace keys by their table overwrites the previous
  // package's identity with winapi@0.4.0 — time 0.2.22, which has two
  // advisories against it (measured), silently becomes a crate that has none.
  const pkgs = parse(fixture('Cargo.lock', CARGO_LOCK));
  assert.ok(!pkgs.some(p => p.name === 'winapi'), '[[patch.unused]] became a package');
  assert.ok(pkgs.some(p => p.name === 'time' && p.version === '0.2.22'),
    'the last real package lost its identity to the trailing [[patch.unused]] block');
});

test('a [[package]] with no version throws rather than being dropped', () => {
  const path = fixture('Cargo.lock', '[[package]]\nname = "libc"\nsource = "registry+x"\n');
  assert.throws(() => parseManifest(path), /Cargo\.lock: \[\[package\]\] at line 1 has no version/);
});

