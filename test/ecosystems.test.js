import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';

import { MANIFESTS, parseManifest } from '../server/services/ecosystems.js';
import { assertPackage } from '../server/services/scanShapes.js';

// The manifest table (v2.53.0).
//
// Everything here is about the same failure: a package name or version derived
// wrongly is not a missing answer, it is a WRONG one. OSV replies "no
// vulnerabilities" for a package that does not exist, so a parser bug is
// recorded as a clean app and reads as safety. Each fixture below is a shape
// that produces exactly that if read naively, and the assertions name the false
// clean rather than the diff.
//
// Fixtures are written to disk and read through parseManifest — the production
// entry point — rather than handed to the parsers as strings, because the file
// read, the filename dispatch and the assertPackage sweep are all part of the
// contract.

const DIR = mkdtempSync(join(tmpdir(), 'crane-eco-'));

function fixture(name, contents) {
  const path = join(DIR, name);
  writeFileSync(path, contents);
  return path;
}

/** Every parser's output must be assertPackage-valid; check it at every call. */
function parse(path, entry) {
  const pkgs = parseManifest(path, entry);
  pkgs.forEach((p, i) => assertPackage(p, `${path}[${i}]`));
  return pkgs;
}

const idsOf = (pkgs) => pkgs.map(p => `${p.name}@${p.version}`).sort();

