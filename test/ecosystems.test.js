test('the table maps six manifests onto OSV ecosystem names', () => {
  assert.deepEqual(
    MANIFESTS.map(m => [m.file, m.ecosystem]),
    [
      ['package-lock.json', 'npm'],
      ['go.sum', 'Go'],
      ['Cargo.lock', 'crates.io'],
      ['Gemfile.lock', 'RubyGems'],
      ['poetry.lock', 'PyPI'],
      ['Pipfile.lock', 'PyPI'],
    ],
    'OSV ecosystem names are matched literally by the API — "cargo", "rubygems" or ' +
    '"pypi" are not errors, they return an empty result set, which records every ' +
    'app in that ecosystem as clean');
  for (const m of MANIFESTS) assert.equal(typeof m.parse, 'function', `${m.file} has no parser`);
});

test('two manifests may share one ecosystem', () => {
  // poetry.lock and Pipfile.lock are both PyPI. The table is keyed by FILE, not
  // by ecosystem, which is what lets a second Python packaging tool be one row.
  const pypi = MANIFESTS.filter(m => m.ecosystem === 'PyPI').map(m => m.file);
  assert.deepEqual(pypi, ['poetry.lock', 'Pipfile.lock']);
});

test('parseManifest dispatches on the filename when no row is passed', () => {
  const path = fixture('Cargo.lock', CARGO_LOCK);
  assert.deepEqual(parse(path), parse(path, MANIFESTS.find(m => m.file === 'Cargo.lock')));
});

test('an unrecognised filename throws rather than returning nothing', () => {
  const path = fixture('requirements.txt', 'django>=4.2\nrequests\n');
  assert.throws(() => parseManifest(path), /no parser for requirements.txt/,
    'an unreadable manifest returned a package list. requirements.txt pins nothing — ' +
    'guessing a version from ">=4.2" answers about a release that may not be installed');
});

test('the recorded error names the manifest that failed', () => {
  // An app can have several manifests. "Unexpected token" on its own does not
  // tell the person reading the scan row which file to open.
  const path = fixture('Pipfile.lock', '{ not json');
  assert.throws(() => parseManifest(path), /^Error: Pipfile\.lock: /);
});

// ---------------------------------------------------------------------------
// npm — generated by `npm install --package-lock-only`, not hand-written
// ---------------------------------------------------------------------------
//
// Produced by npm 10 for a root with a workspace, an aliased dependency
// (mylodash@npm:lodash@4.17.15) and a nested duplicate (async pulls its own
// lodash beside the root's lodash@3). Every trap in one real file.
const NPM_LOCK = JSON.stringify({
  name: 'fixture-root',
  version: '1.0.0',
  lockfileVersion: 3,
  requires: true,
  packages: {
    '': {
      name: 'fixture-root',
      version: '1.0.0',
      workspaces: ['packages/*'],
      dependencies: { async: '2.6.4', lodash: '3.10.1', mylodash: 'npm:lodash@4.17.15' },
    },
    'node_modules/@fixture/design-system': { resolved: 'packages/design-system', link: true },
    'node_modules/async': {
      version: '2.6.4',
      resolved: 'https://registry.npmjs.org/async/-/async-2.6.4.tgz',
      license: 'MIT',
      dependencies: { lodash: '^4.17.14' },
    },
    'node_modules/async/node_modules/lodash': {
      version: '4.18.1',
      resolved: 'https://registry.npmjs.org/lodash/-/lodash-4.18.1.tgz',
      license: 'MIT',
    },
    'node_modules/lodash': {
      version: '3.10.1',
      resolved: 'https://registry.npmjs.org/lodash/-/lodash-3.10.1.tgz',
      license: 'MIT',
    },
    'node_modules/mylodash': {
      name: 'lodash',
      version: '4.17.15',
      resolved: 'https://registry.npmjs.org/lodash/-/lodash-4.17.15.tgz',
      license: 'MIT',
    },
    'packages/design-system': { name: '@fixture/design-system', version: '3.2.1' },
  },
}, null, 2);

test('a real npm lockfile yields only published packages, under their real names', () => {
  const pkgs = parse(fixture('package-lock.json', NPM_LOCK));
  assert.deepEqual(idsOf(pkgs),
    ['async@2.6.4', 'lodash@3.10.1', 'lodash@4.17.15', 'lodash@4.18.1'],
    'the query set is not the published dependency set');
});

test('an aliased dependency is queried under the package name, not the alias', () => {
  // `npm i mylodash@npm:lodash@4.17.15` keys the entry by its INSTALL PATH.
  // OSV has never heard of "mylodash", so it answers clean and a lodash with
  // six advisories against it is recorded green. npm ships aliases itself —
  // string-width-cjs and strip-ansi-cjs arrive through cliui/wrap-ansi — so
  // this is not an exotic case.
  const pkgs = parse(fixture('package-lock.json', NPM_LOCK));
  assert.ok(pkgs.some(p => p.name === 'lodash' && p.version === '4.17.15'),
    'the aliased lodash@4.17.15 was not queried under the name lodash');
  assert.ok(!pkgs.some(p => p.name === 'mylodash'),
    'the alias "mylodash" was sent to OSV — no registry has it, so the answer is a ' +
    'guaranteed false clean for a package with known advisories');
});

test('the root and the workspace member are not dependencies', () => {
  const pkgs = parse(fixture('package-lock.json', NPM_LOCK));
  assert.ok(!pkgs.some(p => p.name === 'fixture-root'),
    'the "" entry is the app itself and is published nowhere');
  // "packages/design-system" carries a real version and is NOT under
  // node_modules, so a parser that slices a fixed 13 characters off every key
  // reports a dependency named "esign-system" — plausible enough in a report,
  // and matching nothing in OSV.
  assert.ok(!pkgs.some(p => p.name.includes('design-system')),
    'the workspace member reached the query set');
  assert.ok(!pkgs.some(p => p.name.includes('/') && !p.name.startsWith('@')),
    'a package name still carries a path fragment; only a scoped name may contain a slash');
});

test('a nested dependency is named for the last node_modules segment', () => {
  const pkgs = parse(fixture('package-lock.json', NPM_LOCK));
  assert.ok(pkgs.some(p => p.name === 'lodash' && p.version === '4.18.1'),
    'the nested async/node_modules/lodash was named after its path — "async/lodash" ' +
    'is not a package, so OSV answers "no vulnerabilities"');
});

test('an npm v1 lockfile is an error, not an empty clean scan', () => {
  const path = fixture('package-lock.json',
    JSON.stringify({ lockfileVersion: 1, dependencies: { lodash: { version: '4.17.15' } } }));
  assert.throws(() => parseManifest(path), /lockfileVersion 1/,
    'a v1 lockfile parsed to zero packages instead of throwing, which records a clean ' +
    'bill of health for a file nothing ever read');
});

