test('Pipfile.lock covers default and develop, with the == pin removed', () => {
  const pkgs = parse(fixture('Pipfile.lock', PIPFILE_LOCK));
  assert.deepEqual(idsOf(pkgs), ['certifi@2023.7.22', 'pytest@7.4.0', 'requests@2.31.0'],
    'develop dependencies run in CI and ship in dev images; leaving them out is the ' +
    'under-report this feature exists to prevent');
  assert.ok(!pkgs.some(p => p.version.startsWith('=')),
    'the "==" pin was passed through as part of the version, which matches no range');
});

test('_meta is not mistaken for a package section', () => {
  const pkgs = parse(fixture('Pipfile.lock', PIPFILE_LOCK));
  assert.ok(!pkgs.some(p => ['hash', 'sources', 'requires', 'pipfile-spec'].includes(p.name)));
});

test('a git requirement pins a ref, not a release, and is left out', () => {
  const pkgs = parse(fixture('Pipfile.lock', PIPFILE_LOCK));
  assert.ok(!pkgs.some(p => p.name === 'internal-lib'),
    'a VCS requirement has no version; inventing one is the requirements.txt mistake');
});

test('an unpinned Pipfile.lock entry is an error, not a guess', () => {
  // pipenv always writes "==<version>". Anything else means the file is not
  // what it claims to be, and a range has no single installed version — an
  // 'error' is visible and gets fixed, a quietly dropped package is not.
  const path = fixture('Pipfile.lock', JSON.stringify({ default: { django: { version: '>=4.2' } } }));
  assert.throws(() => parseManifest(path), /"django" in default is not pinned/,
    'a range was accepted as a version, which answers confidently about a release ' +
    'that may not be installed');
});

test('a JSON file with no default or develop section is not a Pipfile.lock', () => {
  const path = fixture('Pipfile.lock', JSON.stringify({ _meta: { 'pipfile-spec': 6 } }));
  assert.throws(() => parseManifest(path), /no "default" or "develop" section/,
    'an unrecognised JSON file parsed to zero packages — a clean scan for a file ' +
    'nothing understood');
});

