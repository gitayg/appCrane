test('every package from every parser carries its table row ecosystem', () => {
  // The ecosystem travels WITH the package rather than being applied at query
  // time, which is what lets one scan mix ecosystems in a single OSV batch. A
  // parser that forgets it emits a package the asserter rejects.
  const cases = [
    ['package-lock.json', NPM_LOCK, 'npm'],
    ['yarn.lock', YARN_V1, 'npm'],
    ['yarn.lock', YARN_BERRY, 'npm'],
    ['pnpm-lock.yaml', PNPM_LOCK_9, 'npm'],
    ['composer.lock', COMPOSER_LOCK, 'Packagist'],
    ['go.sum', GO_SUM, 'Go'],
    ['Cargo.lock', CARGO_LOCK, 'crates.io'],
    ['Gemfile.lock', GEMFILE_LOCK, 'RubyGems'],
    ['poetry.lock', POETRY_LOCK, 'PyPI'],
    ['Pipfile.lock', PIPFILE_LOCK, 'PyPI'],
  ];
  for (const [file, contents, ecosystem] of cases) {
    const pkgs = parse(fixture(file, contents));
    assert.ok(pkgs.length > 0, `${file} parsed to nothing`);
    for (const p of pkgs) {
      assertPackage(p, file);
      assert.equal(p.ecosystem, ecosystem, `${file} emitted ecosystem ${p.ecosystem}`);
    }
  }
});
