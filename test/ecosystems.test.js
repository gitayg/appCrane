test('only the 4-space GEM entries are installed gems', () => {
  const pkgs = parse(fixture('Gemfile.lock', GEMFILE_LOCK));
  assert.deepEqual(idsOf(pkgs), [
    'actionpack@7.0.4', 'nokogiri@1.13.5', 'racc@1.6.0', 'rack@2.2.4', 'rails@7.1.0.beta1',
  ], 'the specs block was read without regard to indentation');
});

test('a 6-space dependency constraint is not a gem at that version', () => {
  // `      rack (~> 2.0, >= 2.2.0)` is what actionpack ASKS FOR, not what is
  // installed. Read as a gem it queries rack at version "~> 2.0, >= 2.2.0",
  // which matches nothing — and it displaces the real rack 2.2.4 in any
  // dedupe keyed on name.
  const pkgs = parse(fixture('Gemfile.lock', GEMFILE_LOCK));
  assert.ok(!pkgs.some(p => /[~>=,]/.test(p.version)),
    'a dependency constraint was recorded as an installed version');
  assert.ok(!pkgs.some(p => p.name === 'actionview'),
    'actionview appears only as a constraint under actionpack and is not installed here');
});

test('GIT and PATH sections are not rubygems.org packages', () => {
  const pkgs = parse(fixture('Gemfile.lock', GEMFILE_LOCK));
  assert.ok(!pkgs.some(p => p.name === 'railties'),
    'a gem resolved from a git checkout was queried against RubyGems, where its version ' +
    'need not correspond to any published release');
  assert.ok(!pkgs.some(p => p.name === 'billing'),
    'a PATH gem is local to the app and is published nowhere');
});

test('the platform suffix is stripped and the dotted prerelease is not', () => {
  // Measured against the live OSV API, and the reason this line exists:
  //   activerecord 7.0.0              -> 4 advisories
  //   activerecord 7.0.0-x86_64-linux -> 1 advisory
  // The three that vanish are the ones whose range opens at introduced 7.0.0 —
  // Ruby reads the hyphen as a prerelease separator, so the suffixed string
  // sorts BELOW the plain version and falls outside the range. Three silent
  // false cleans from one platform suffix. Ruby's own prereleases use dots
  // (7.1.0.beta1), so cutting at the first hyphen only ever removes a platform.
  const byName = Object.fromEntries(parse(fixture('Gemfile.lock', GEMFILE_LOCK))
    .map(p => [p.name, p.version]));
  assert.equal(byName.nokogiri, '1.13.5',
    'the platform suffix was left on the version, which moves it below every ' +
    '"introduced" boundary and hides the advisories that open there');
  assert.equal(byName.rails, '7.1.0.beta1',
    'a dotted Ruby prerelease was truncated — that is a different version');
});

test('a 4-space line inside GEM specs that is not "name (version)" throws', () => {
  const path = fixture('Gemfile.lock', 'GEM\n  remote: https://rubygems.org/\n  specs:\n    rack 2.2.4\n');
  assert.throws(() => parseManifest(path), /Gemfile\.lock: line 4/,
    'an unparseable spec line was skipped, so the gem is never queried and the app ' +
    'reads as clean');
});

